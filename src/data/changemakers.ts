const markerColors = ["#f4a47e", "#67dfc4", "#e7cf7c", "#8dc7ee", "#d7a2df", "#a9d480", "#f19bac"];

export function categoryColor(category: string) {
  const categories = [...new Set(changemakers.map((person) => person.category))].sort();
  const index = categories.indexOf(category);
  return markerColors[(index < 0 ? 0 : index) % markerColors.length] ?? "#67dfc4";
}

export function categoryTone(category: string) {
  const categories = [...new Set(changemakers.map((person) => person.category))].sort();
  const index = categories.indexOf(category);
  return ["category-tone-0", "category-tone-1", "category-tone-2", "category-tone-3", "category-tone-4", "category-tone-5", "category-tone-6"][(index < 0 ? 0 : index) % 7] ?? "category-tone-0";
}

