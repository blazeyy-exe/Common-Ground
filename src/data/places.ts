// Derive the sorted lists the explorer filters read from, so hand edits to the
// taxonomy above can never produce unsorted or duplicated options.
export const countriesByRegion: RegionGroup[] = regionGroups
  .map(({ region, countries }) => ({
    region,
    countries: [...countries].sort((a, b) => a.localeCompare(b)),
  }))
  .sort((a, b) => a.region.localeCompare(b.region));

export const regionNames: string[] = countriesByRegion.map((group) => group.region);

export const countryNames: string[] = [
  ...new Set(countriesByRegion.flatMap((group) => group.countries)),
].sort((a, b) => a.localeCompare(b));